"""Intervals for the held-out prediction comparison of section 4.7.

`inv009/head_to_head.py` reports each candidate's typical absolute miss as the
across-people median of each person's mean absolute error on held-out nights, and
writes no interval. This script reads the per-person table that script committed
(`results/inv009_head_to_head.parquet`) and adds a 95% percentile interval from
2,000 bootstrap draws that resample people, overall and within each of the six
cohorts. It also gives the paired difference of each candidate against the static
1800 rule: the difference between the two across-people medians, with both
medians recomputed on the same resampled people in every draw. For the entered
setting, which was scored for fewer people, the difference is taken over the
people who have both. Nothing is refitted, so the point values are those of the
committed JSON.

The unit of resampling is the person, because each person contributes one mean
absolute error and the nights within a person are not independent.

Expected sign, written before the run. V2 minus the 1800 rule is positive with an
interval far above zero overall and in every cohort. V1 minus the rule is positive
overall and in five cohorts by 2 to 6 mg/dL, and negative in IOBP2 by about
1.6 mg/dL; of these, the IOBP2 interval and some of the smaller-cohort intervals are
expected to include zero. The best fitted single value against the rule is
expected to include zero overall, since the two medians differ by 0.3 mg/dL.

    python3 -m inv009.head_to_head_intervals

Outputs results/inv009_head_to_head_intervals.{json,md} (aggregates only).
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

N_BOOT = 2000
SEED = 0
BASE = "rule_1800"
CANDS = ("rule_1800", "fitted_flat", "v1", "entered", "root_tdd", "v2")
LABEL = {"rule_1800": "Static 1800 rule", "fitted_flat": "Best fitted single value",
         "v1": "V1", "entered": "Entered setting", "root_tdd": "Historical 355/sqrt(TDD)",
         "v2": "V2"}
STUDY_ORDER = ("Loop", "ReplaceBG", "DCLP3", "DCLP5", "PEDAP", "IOBP2")
RESULTS = Path(__file__).resolve().parent.parent / "results"


def boot_medians(R: pd.DataFrame, n_boot: int = N_BOOT, seed: int = SEED) -> dict:
    """Median of each candidate and median difference against BASE, people resampled."""
    rng = np.random.default_rng(seed)
    n = len(R)
    out: dict = {"n_people": int(n), "candidates": {}, "vs_rule_1800": {}}
    idx = rng.integers(0, n, (n_boot, n))
    base = R[f"mae_{BASE}"].to_numpy(float)
    for c in CANDS:
        v = R[f"mae_{c}"].to_numpy(float)
        ok = np.isfinite(v)
        if ok.sum() < 10:
            continue
        # each draw: median over the drawn people who have this candidate
        vb = np.where(ok[idx], v[idx], np.nan)
        meds = np.nanmedian(vb, axis=1)
        lo, hi = np.percentile(meds, [2.5, 97.5])
        out["candidates"][c] = dict(mae=float(np.median(v[ok])), lo=float(lo), hi=float(hi),
                                    n=int(ok.sum()))
        if c == BASE:
            continue
        both = ok & np.isfinite(base)
        bb = np.where(both[idx], base[idx], np.nan)
        diffs = np.nanmedian(vb * np.where(both[idx], 1, np.nan), axis=1) - np.nanmedian(bb, axis=1)
        point = float(np.median(v[both]) - np.median(base[both]))
        lo, hi = np.percentile(diffs, [2.5, 97.5])
        verdict = ("interval above zero" if lo > 0 else
                   "interval below zero" if hi < 0 else "interval includes zero")
        out["vs_rule_1800"][c] = dict(diff=point, lo=float(lo), hi=float(hi),
                                      n=int(both.sum()), verdict=verdict)
    return out


def self_check() -> None:
    """A constant offset must come back exactly, with a degenerate interval."""
    rng = np.random.default_rng(1)
    base = rng.uniform(20, 40, 200)
    R = pd.DataFrame({f"mae_{c}": base + (5.0 if c == "v2" else 0.0) for c in CANDS})
    r = boot_medians(R, n_boot=200)
    d = r["vs_rule_1800"]["v2"]
    assert abs(d["diff"] - 5.0) < 1e-9 and abs(d["lo"] - 5.0) < 1e-9 and d["verdict"] == "interval above zero"
    assert r["candidates"]["v1"]["lo"] < r["candidates"]["v1"]["hi"]   # the bootstrap varies


def markdown(res: dict) -> str:
    L = ["# Held-out prediction in the public archives, with intervals", "",
         "Generated by `inv009/head_to_head_intervals.py` from `results/inv009_head_to_head.parquet`. "
         "Typical absolute miss is the across-people median of each person's mean absolute error on "
         "held-out nights, mg/dL. Intervals are 95% percentile intervals from "
         f"{N_BOOT} bootstrap draws resampling people. Differences are candidate minus the static "
         "1800 rule, on the same resampled people; for the entered setting, on the people who have it.", ""]
    for label, r in [("All cohorts", res["overall"])] + [(k, v) for k, v in res["by_study"].items()]:
        L += [f"## {label} ({r['n_people']} people)", "",
              "| Candidate | People | Typical absolute miss (95% interval) | Minus 1800 rule (95% interval) | Verdict |",
              "|---|---:|---|---|---|"]
        for c in CANDS:
            if c not in r["candidates"]:
                continue
            m = r["candidates"][c]
            if c == BASE:
                L.append(f"| {LABEL[c]} | {m['n']} | {m['mae']:.1f} ({m['lo']:.1f} to {m['hi']:.1f}) | - | - |")
            else:
                d = r["vs_rule_1800"][c]
                L.append(f"| {LABEL[c]} | {m['n']} | {m['mae']:.1f} ({m['lo']:.1f} to {m['hi']:.1f}) | "
                         f"{d['diff']:+.1f} ({d['lo']:+.1f} to {d['hi']:+.1f}), n={d['n']} | {d['verdict']} |")
        L.append("")
    return "\n".join(L)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--table", type=Path, default=RESULTS / "inv009_head_to_head.parquet")
    ap.add_argument("--out", type=Path, default=RESULTS)
    a = ap.parse_args()
    self_check()
    R = pd.read_parquet(a.table)
    assert not R.subject_id.duplicated().any()
    res = {"source": a.table.name, "overall": boot_medians(R), "by_study": {}}
    for s in STUDY_ORDER:
        res["by_study"][s] = boot_medians(R[R.study == s].reset_index(drop=True))
    (a.out / "inv009_head_to_head_intervals.json").write_text(json.dumps(res, indent=1))
    md = markdown(res)
    (a.out / "inv009_head_to_head_intervals.md").write_text(md)
    print(md)
    return 0


if __name__ == "__main__":
    sys.exit(main())
