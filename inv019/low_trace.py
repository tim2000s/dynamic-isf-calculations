#!/usr/bin/env python3
"""INV-019: what glucose and what insulin preceded the time below 54 mg/dL in each arm.

The first run read harm on the low side for the candidate against `profile, autosens`, and
its docstring inferred from the arms that the rise went with how much more insulin than the
profile the rule asked for above target. No run was traced. This reads the raw runs of seed
101 already on disk (results/inv019_raw/) and simulates nothing.

Method, with its choices. A low is a run of consecutive five-minute steps with true glucose
below 54 mg/dL, from day 8. Each low is filed under the highest true glucose in the four
hours before it began, in four bands: below 140, 140 to 180, 180 to 250 and above 250
mg/dL. Four hours is a choice, near the time over which a correction does most of its work.
A person's time below 54 is then split by band, and the bands add up to the figure the
outcome report gives. Each arm is compared with `profile, pinned` on the people who
completed both runs, with a 95% interval from resampling people. The placebo is the null
check and is read first.
  A second table takes the candidate's lows alone. For each, the insulin delivered in the
  four hours before it began is compared with what the reference run delivered to the same
  person over the same clock hours. The two runs share meals and sensor noise and have
  drifted apart by then, so this is a difference between two runs and not the dose that
  caused the low.

Expected before the run. The candidate asks for more insulin than the profile above 140
mg/dL and less below it. Its extra time below 54 is therefore expected in lows that follow
a peak above 180 mg/dL, with no rise in lows that follow a peak below 140. The candidate
run is expected to have delivered more insulin than the reference in the four hours before
its lows. `candidate, anchor 180` asks for less insulin than the profile below 180 and is
expected to show no rise in any band. `profile x 0.7` asks for more at every glucose and is
expected to rise in every band. The placebo's intervals are expected to include zero.

    python -m inv019.low_trace

from the repository root with DYNISF_ROOT unset. Writes results/inv019_low_trace.md. The
per-person rows stay out of git.

Results
(none yet)
"""
from __future__ import annotations

import numpy as np
import pandas as pd

from inv019.outcome_test import NULL, REFERENCE, RESULTS, WARM_DAYS, _f, mean_ci

RAW = RESULTS / "inv019_raw"
BEFORE = 48                                    # steps: four hours of five minutes
EDGES, BANDS = (140.0, 180.0, 250.0), ("below 140", "140 to 180", "180 to 250", "above 250")
ARMS = (NULL, "candidate", "candidate, Trio limits", "candidate, anchor 180", "flat above 100",
        "logarithmic, matched", "Trio sigmoid", "profile x 0.7")


def lows(bg) -> list[tuple[int, int, float]]:
    """(first step, steps, highest glucose in the four hours before) for each low."""
    under = np.asarray(bg) < 54.0
    starts = np.flatnonzero(under & ~np.r_[False, under[:-1]])
    ends = np.flatnonzero(under & ~np.r_[under[1:], False])
    return [(int(s), int(e - s + 1), float(np.max(bg[max(s - BEFORE, 0):s + 1]))) for s, e in zip(starts, ends)]


def by_band(bg) -> np.ndarray:
    """Percentage of the series spent below 54 mg/dL, split by the band of each low's peak."""
    out = np.zeros(len(BANDS))
    for _, n, peak in lows(bg):
        out[np.searchsorted(EDGES, peak, side="right")] += n
    return 100.0 * out / len(bg)


def run(arm: str, subject: str):
    z = np.load(RAW / f"{arm}__{subject}.npz")
    warm = z["minutes"] >= WARM_DAYS * 1440.0
    return bool(z["completed"]), z["bg"][warm].astype(float), z["insulin"][warm].astype(float)


def main() -> None:
    people = sorted(p.stem.split("__")[1] for p in RAW.glob(f"{REFERENCE}__*.npz"))
    ref = {s: run(REFERENCE, s) for s in people}
    L = ["# INV-019: what preceded the time below 54 mg/dL", "",
         "Generated by `inv019/low_trace.py` from the raw runs of seed 101. Time below 54 mg/dL as a "
         "percentage of time from day 8, split by the highest true glucose in the four hours before each "
         f"low began. Each arm less `{REFERENCE}`, mean over people who completed both runs with a 95% "
         "interval from resampling people. The first row is the null check.", "",
         "| Arm | People | Lows per person, arm / reference | " + " | ".join(BANDS) + " | All |",
         "|---|---:|---:|" + "---:|" * (len(BANDS) + 1)]
    for arm in ARMS:
        rows = [(len(lows(a[1])), len(lows(r[1])), by_band(a[1]) - by_band(r[1]))
                for s in people for a, r in [(run(arm, s), ref[s])] if a[0] and r[0]]
        d = np.array([x[2] for x in rows])
        L.append(f"| {arm} | {len(rows)} | {np.mean([x[0] for x in rows]):.1f} / {np.mean([x[1] for x in rows]):.1f} | "
                 + " | ".join(_f(mean_ci(d[:, k])) for k in range(len(BANDS))) + f" | {_f(mean_ci(d.sum(axis=1)))} |")

    per, peaks = [], []
    for s in people:
        (ok, bg, ins), r = run("candidate", s), ref[s]
        found = [(i, peak) for i, _, peak in lows(bg) if i >= BEFORE] if ok and r[0] else []
        if found:
            per.append(np.mean([ins[i - BEFORE:i].sum() - r[2][i - BEFORE:i].sum() for i, _ in found]))
            peaks += [(peak, ins[i - BEFORE:i].sum(), r[2][i - BEFORE:i].sum()) for i, peak in found]
    t = pd.DataFrame(peaks, columns=["peak", "arm", "ref"])
    t["band"] = pd.Categorical.from_codes(np.searchsorted(EDGES, t.peak, side="right"), BANDS)
    L += ["", "## Insulin in the four hours before the candidate's lows", "",
          f"{len(t)} lows in {len(per)} people. Over people, the candidate run delivered "
          f"{_f(mean_ci(per))} U more than the reference run over the same four clock hours.", "",
          "| Peak before the low, mg/dL | Lows | Median insulin in the four hours, candidate run, U | The reference run over the same hours, U |",
          "|---|---:|---:|---:|"]
    L += [f"| {b} | {len(g)} | {g.arm.median():.2f} | {g.ref.median():.2f} |" for b, g in t.groupby("band", observed=False) if len(g)]
    (RESULTS / "inv019_low_trace.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
