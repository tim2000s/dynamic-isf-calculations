"""Checks on the INV-020 method, written to results/inv020_checks.md.

The request identity: at the logged sensitivity, (min(eventual glucose, minPredBG) - target)
/ ISF against the logged insulin requirement, to 0.05 U, on every decision with a nonzero
logged requirement and an unclamped prediction (oref logs only the requirement above target).

    python3 -m inv020.checks
"""

from __future__ import annotations

import psycopg2

from inv008.config import DB
from inv020.replay import RESULTS

# share of decisions with a logged requirement that (min(eventual, minPredBG) - target) / ISF reproduces
SHARE = (
    "count(*), avg((abs((least(ev, coalesce(mp, ev)) - target) / s - req) < 0.05)::int)"
)
KEEP = "req <> 0 AND s > 0 AND least(ev, coalesce(mp, ev)) > 39 AND least(ev, coalesce(mp, ev)) < 401"
QUERIES = {
    "AndroidAPS (Commons)": "SELECT "
    + SHARE
    + " FROM (SELECT sug_eventualbg ev, reason_minpredbg mp, "
    "sug_current_target target, sug_isf s, sug_insulinreq req FROM oref_v6) t WHERE "
    + KEEP,
    "oref0 (Commons)": "SELECT "
    + SHARE
    + " FROM (SELECT sug_eventualbg ev, reason_minpredbg mp, "
    "sug_current_target target, sug_isf s, sug_insulinreq req FROM oref_v7) t WHERE "
    + KEEP,
}


def main() -> None:
    L = [
        "# INV-020 checks",
        "",
        "Generated by `inv020/checks.py`.",
        "",
        "## The request identity at the logged sensitivity",
        "",
        "| Source | Decisions with a requirement | Reproduced to 0.05 U |",
        "|---|---:|---:|",
    ]
    with psycopg2.connect(**DB) as conn, conn.cursor() as cur:
        for name, q in QUERIES.items():
            cur.execute(q)
            n, share = cur.fetchone()
            L.append(f"| {name} | {n:,} | {100 * share:.1f}% |")
    (RESULTS / "inv020_checks.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
